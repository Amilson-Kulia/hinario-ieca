  /// Retorna um texto traduzido.
  ///
  /// Se o idioma ou a chave não existir, utiliza português
  /// como fallback.
  static String texto(
    String idioma,
    String chave, {
    Map<String, String>? parametros,
  }) {
    String texto =
        _textos[idioma]?[chave] ??
        _textos['portugues']?[chave] ??
        chave;

    if (parametros != null) {
      parametros.forEach((nome, valor) {
        texto = texto.replaceAll('{$nome}', valor);
      });
    }

    return texto;
  }

  /// Verifica se existe tradução para determinado idioma.
  static bool idiomaExiste(String idioma) {
    return _textos.containsKey(idioma);
  }
